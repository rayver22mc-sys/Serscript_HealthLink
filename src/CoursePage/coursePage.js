function togglePhoneBar(){
    if(document.getElementById("phoneMenuBar").style.display === "flex"){
        document.getElementById("phoneMenuBar").style.display = "none";
    }else{
        document.getElementById("phoneMenuBar").style.display = "flex";
    }
}

